"""Regenerate characters.js from tools/characters.source.json.

Usage: python3 tools/build_data.py
Drops retired characters (those with a validUntil) and strips fields the game doesn't use.
"""
import json, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
src = json.loads((root / "tools" / "characters.source.json").read_text())
keep = ["name", "homeWorld", "firstAppearance", "species", "abilities"]
out = [{k: c[k] for k in keep} for c in src if "validUntil" not in c]
js = "// Generated by tools/build_data.py — edit tools/characters.source.json instead.\nwindow.CHARACTERS = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n"
(root / "characters.js").write_text(js)
print(f"wrote {len(out)} characters")
